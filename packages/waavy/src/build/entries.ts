/**
 * Generated entry files.
 *
 * `waavy build` writes one server entry (all pages) and one client entry per
 * page into a temporary directory *inside the project*, so Bun resolves
 * `react` and `@bundt/waavy` from the project's own `node_modules`. The
 * generated source is deliberately tiny; all behavior lives in
 * `@bundt/waavy/entry-server` and `@bundt/waavy/browser`.
 */

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';

import type { ResolvedPage } from './config-loader';

/** Specifier the server entry imports `defineRelease` from. */
export const ENTRY_SERVER_SPECIFIER = '@bundt/waavy/entry-server';

/** Specifier client entries import `hydrate` from. */
export const BROWSER_SPECIFIER = '@bundt/waavy/browser';

/** Notice placed at the top of every generated file. */
const GENERATED_HEADER = '// Generated by `waavy build`. Do not edit.';

/** Source of the server entry registering every page under its ID. */
export function serverEntrySource(buildId: string, pages: readonly ResolvedPage[]): string {
  const imports = pages.map((page, index) => `import Page${index} from ${JSON.stringify(page.file)};`);
  const registrations = pages.map((page, index) => `    ${JSON.stringify(page.id)}: Page${index}`);
  return [
    GENERATED_HEADER,
    `import { defineRelease } from ${JSON.stringify(ENTRY_SERVER_SPECIFIER)};`,
    ...imports,
    '',
    'export const release = defineRelease({',
    `  buildId: ${JSON.stringify(buildId)},`,
    '  pages: {',
    registrations.join(',\n'),
    '  }',
    '});',
    ''
  ].join('\n');
}

/** Source of the client entry that hydrates one page. */
export function clientEntrySource(buildId: string, page: ResolvedPage): string {
  return [
    GENERATED_HEADER,
    `import { hydrate } from ${JSON.stringify(BROWSER_SPECIFIER)};`,
    `import Page from ${JSON.stringify(page.file)};`,
    '',
    `hydrate(Page, { buildId: ${JSON.stringify(buildId)} });`,
    ''
  ].join('\n');
}

/** Paths of the entry files written by {@link writeEntries}. */
export type WrittenEntries = {
  /** Absolute path of the server entry. */
  server: string;
  /** Directory containing the client entries; the client build's `root`. */
  clientRoot: string;
  /** Page ID → absolute path of its client entry. */
  clients: ReadonlyMap<string, string>;
};

/**
 * Writes every entry into `dir`. Client entries are named after their page ID
 * (`account/settings` → `client/account/settings.tsx`) so output file names
 * stay recognizable.
 */
export async function writeEntries(
  dir: string,
  buildId: string,
  pages: readonly ResolvedPage[]
): Promise<WrittenEntries> {
  const server = join(dir, 'server', 'entry.tsx');
  const clientRoot = join(dir, 'client');
  await writeSource(server, serverEntrySource(buildId, pages));

  const clients = new Map<string, string>();
  for (const page of pages) {
    const file = join(clientRoot, `${page.id}.tsx`);
    await writeSource(file, clientEntrySource(buildId, page));
    clients.set(page.id, file);
  }
  return { server, clientRoot, clients };
}

async function writeSource(file: string, source: string): Promise<void> {
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, source, 'utf8');
}
