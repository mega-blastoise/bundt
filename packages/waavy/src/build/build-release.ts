/**
 * `waavy build`: project → release directory.
 *
 * Steps:
 * 1. load and resolve `waavy.config.*`;
 * 2. generate entry files inside the project (`node_modules/.cache/waavy`);
 * 3. bundle client and server into a staging directory;
 * 4. derive and validate the manifest, write it;
 * 5. replace the previous release with the staging directory.
 *
 * Temporary files are always removed; on failure the previous release is
 * left untouched.
 *
 * See ARCHITECTURE.md §4.2 and spikes/P1_SPIKES.md.
 */

import { join, relative, resolve, sep } from 'node:path';

import { type Manifest, MANIFEST_VERSION, parseManifest, RELEASE_CLIENT_DIR, RELEASE_SERVER_DIR } from '../core/manifest';
import { PROTOCOL_VERSION } from '../core/protocol';
import { RELEASE_ABI_VERSION } from '../core/release-abi';
import { WAAVY_VERSION } from '../core/version';
import { createBuildId } from './build-id';
import { bundleClient, bundleServer } from './bundles';
import { loadConfig } from './config-loader';
import { writeEntries } from './entries';
import { createStagingDir, publishStagingDir, removeQuietly, writeManifest } from './release-dir';

/** Where generated entries are written, relative to the project root. */
const ENTRIES_CACHE_DIR = join('node_modules', '.cache', 'waavy', 'build');

/** Options for {@link buildRelease}. */
export type BuildReleaseOptions = {
  /** Directory searched for `waavy.config.*`. */
  root: string;
  /** Explicit config file, relative to `root` or absolute. */
  configPath?: string;
  /** Overrides the config's `outDir` (absolute, or relative to the working directory). */
  outDir?: string;
  /** Minify and use production React. Defaults to `true`. */
  production?: boolean;
};

/** A successfully written release. */
export type BuiltRelease = {
  /** Absolute path of the release directory. */
  dir: string;
  manifest: Manifest;
};

/**
 * Builds a release for the project.
 *
 * @throws {WaavyError} `CONFIG_INVALID` or `BUILD_FAILED`.
 */
export async function buildRelease(options: BuildReleaseOptions): Promise<BuiltRelease> {
  const loaded = await loadConfig({ root: options.root, configPath: options.configPath });
  const production = options.production ?? true;
  const buildId = createBuildId();
  const entriesDir = join(loaded.projectRoot, ENTRIES_CACHE_DIR, buildId);
  const outDir = options.outDir === undefined ? loaded.outDir : resolve(options.outDir);
  const staging = await createStagingDir(outDir, buildId);

  try {
    const entries = await writeEntries(entriesDir, buildId, loaded.pages);

    // Both bundles run concurrently; `settleAll` waits for both before
    // surfacing a failure so cleanup never races a still-running build.
    const [pages, serverBundle] = await settleAll([
      bundleClient({
        entries: entries.clients,
        entriesRoot: entries.clientRoot,
        outDir: join(staging, RELEASE_CLIENT_DIR),
        production
      }),
      bundleServer({ entry: entries.server, outDir: join(staging, RELEASE_SERVER_DIR), production })
    ] as const);

    // Validate what we are about to publish with the same schema runtimes use,
    // so a release that builds is a release that opens.
    const manifest = parseManifest(
      {
        manifestVersion: MANIFEST_VERSION,
        abi: RELEASE_ABI_VERSION,
        protocolVersion: PROTOCOL_VERSION,
        waavyVersion: WAAVY_VERSION,
        buildId,
        publicPath: loaded.config.publicPath,
        renderDefaults: { timeoutMs: loaded.config.render.timeoutMs },
        server: toPosixPath(relative(staging, serverBundle)),
        pages
      },
      'generated by waavy build'
    );
    await writeManifest(staging, manifest);
    await publishStagingDir(staging, outDir, buildId);
    return { dir: outDir, manifest };
  } catch (error) {
    await removeQuietly(staging);
    throw error;
  } finally {
    await removeQuietly(entriesDir);
  }
}

/**
 * Like `Promise.all`, but waits for every promise to settle before rejecting
 * with the first failure (in input order).
 */
async function settleAll<const T extends readonly unknown[]>(
  promises: { readonly [K in keyof T]: Promise<T[K]> }
): Promise<T> {
  const results = await Promise.allSettled(promises);
  const failure = results.find((result) => result.status === 'rejected');
  if (failure !== undefined) throw failure.reason;
  return results.map((result) => (result as PromiseFulfilledResult<unknown>).value) as unknown as T;
}

function toPosixPath(path: string): string {
  return path.split(sep).join('/');
}
